    public static string Get(string key) => Get(key, Language);

    public static string Get(string key, string lang) =>
        All.TryGetValue(key, out var t) ? (lang == "en" ? t.En : t.El) : key;

    public static string Format(string key, params object?[] args) => string.Format(Get(key), args);

    public static string Kind(ItemKind k) => Get(k switch
    {
        ItemKind.Product => "kind.product",
        ItemKind.Merchandise => "kind.merchandise",
        _ => "kind.raw",
    });

    public static string Unit(QtyUnit u) => Get("unit." + u.ToString().ToLowerInvariant());

    public static string Reason(PriceReason r) => Get("reason." + r);

    public static string Reasons(PriceReason r) => string.Join(", ", r.Split().Select(Reason));

